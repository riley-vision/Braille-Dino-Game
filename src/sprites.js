// Pixel art for the picture sighted guides see, in the style of the
// original game: a grey T-rex, cacti and pterodactyls on a desert line.
// Drawn for this project (not the original's sprite sheet). '#' is ink,
// 'o' is a hole in the ink (the eye), anything else is empty.
var DinoSprites = (function () {
  'use strict';
  const T_REX_TOP = [
    '............########..',
    '...........##o#######.',
    '...........##########.',
    '...........##########.',
    '...........##########.',
    '...........#####......',
    '...........########...',
    '#.........#####.......',
    '#........######.......',
    '##......########......',
    '###....##########.....',
    '####..########..#.....',
    '##############........',
    '.#############........',
    '..###########.........',
    '...#########..........',
    '....#######...........',
  ];
  const LEGS_A = [
    '.....###.##...........',
    '.....##...#...........',
    '.....#....#...........',
    '.....##...##..........',
  ];
  const LEGS_B = [
    '.....##..###..........',
    '.....#....##..........',
    '.....#................',
    '.....##...............',
  ];
  const LEGS_C = [
    '.....###.###..........',
    '.....##...##..........',
    '.....#.....#..........',
    '.....##....##.........',
  ];
  const DEAD_TOP = T_REX_TOP.map((row, i) => (i === 1 ? '...........##.#######.' : i === 0 ? '............#o######..' : i === 2 ? '...........###o######.' : row));

  const T_REX_DUCK = [
    '.........................########...',
    '#........................##o#######.',
    '##.......##########################.',
    '####..#############################.',
    '.##################################.',
    '..############################......',
    '...##############################...',
    '.....#####....#####.................',
    '......##.......##...................',
    '......#........#....................',
    '......##.......##...................',
  ];
  const T_REX_DUCK_B = T_REX_DUCK.slice(0, 7).concat([
    '.....#####....#####.................',
    '.......##.....##....................',
    '........#....#......................',
    '........##...##.....................',
  ]);

  const CACTUS_SMALL = [
    '...###...',
    '..#####..',
    '..#####..',
    '#.#####..',
    '#.#####.#',
    '#.#####.#',
    '#.#####.#',
    '#.#####.#',
    '#######.#',
    '.######.#',
    '..#######',
    '..#####..',
    '..#####..',
    '..#####..',
    '..#####..',
    '..#####..',
    '..#####..',
    '..#####..',
  ];
  const CACTUS_LARGE = [
    '.....###.....',
    '....#####....',
    '....#####....',
    '....#####....',
    '##..#####....',
    '##..#####..##',
    '##..#####..##',
    '##..#####..##',
    '##..#####..##',
    '##..#####..##',
    '##..#####..##',
    '##..#####..##',
    '#########..##',
    '.########..##',
    '....#########',
    '....########.',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
    '....#####....',
  ];
  // Facing left, towards the dino: beak, head, body, and a wing up or down.
  const BIRD_UP = [
    '.........#..............',
    '.........##.............',
    '.........###............',
    '.........####...........',
    '.........#####..........',
    '...#.....######.........',
    '..##.....#######........',
    '.####....########.......',
    '######################..',
    '....###################.',
    '........############....',
    '..........########......',
  ];
  const BIRD_DOWN = [
    '...#....................',
    '..##....................',
    '.####...................',
    '######################..',
    '....###################.',
    '........###########.....',
    '.........#######........',
    '.........#####..........',
    '.........###............',
    '.........##.............',
    '.........#..............',
  ];

  // The same height for both frames, with the body on the same row, so
  // the bird flaps without bobbing.
  const EMPTY = '.'.repeat(BIRD_UP[0].length);
  const BIRD_UP_ALIGNED = BIRD_UP.concat(Array(4).fill(EMPTY));
  const BIRD_DOWN_ALIGNED = Array(5).fill(EMPTY).concat(BIRD_DOWN);
  const CLOUD = [
    '........#####.......',
    '.......#.....##.....',
    '....###........#....',
    '...#............#...',
    '.##..............#..',
    '#.................##',
    '####################',
  ];

  /** Draws a sprite with its bottom left corner at (x, y), each map pixel a
   * square of size px. */
  function draw(ctx, map, x, y, px, ink, hole) {
    const top = y - map.length * px;
    for (let r = 0; r < map.length; r++) {
      const row = map[r];
      for (let c = 0; c < row.length; c++) {
        const ch = row[c];
        if (ch === '#') {
          ctx.fillStyle = ink;
          ctx.fillRect(x + c * px, top + r * px, px, px);
        } else if (ch === 'o' && hole) {
          ctx.fillStyle = hole;
          ctx.fillRect(x + c * px, top + r * px, px, px);
        }
      }
    }
  }
  const size = (map, px) => ({ w: map[0].length * px, h: map.length * px });

  return {
    standing: (step) => T_REX_TOP.concat([LEGS_A, LEGS_B, LEGS_A, LEGS_C][step % 2 ? 1 : 0]),
    jumping: () => T_REX_TOP.concat(LEGS_C),
    dead: () => DEAD_TOP.concat(LEGS_C),
    ducking: (step) => (step % 2 ? T_REX_DUCK_B : T_REX_DUCK),
    cactus: (large) => (large ? CACTUS_LARGE : CACTUS_SMALL),
    bird: (step) => (step % 2 ? BIRD_DOWN_ALIGNED : BIRD_UP_ALIGNED),
    cloud: () => CLOUD,
    draw,
    size,
  };
})();
